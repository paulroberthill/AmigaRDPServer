#!/usr/bin/env python3
"""Generate tests/crypto_vectors.h: known answers for test_crypto.c."""
import hashlib, random, sys

rnd = random.Random(1234)
buf = bytes((i * 7 + 3) & 0xff for i in range(1000))
lens = [0, 1, 55, 56, 63, 64, 65, 119, 120, 999]
o = ["/* generated by crypto_vectors.py - do not edit */"]
o.append("static const int hash_lens[] = {%s};" % ", ".join(map(str, lens)))
o.append("static const char *md5_want[] = {%s};" % ", ".join('"%s"' % hashlib.md5(buf[:n]).hexdigest() for n in lens))
o.append("static const char *sha1_want[] = {%s};" % ", ".join('"%s"' % hashlib.sha1(buf[:n]).hexdigest() for n in lens))
o.append("static const struct { const char *n, *b, *e, *want; } rsa_vec[] = {")
for bits in (512, 512, 512, 1024, 2048):
    n = rnd.getrandbits(bits) | (1 << (bits - 1)) | 1
    if rnd.random() < 0.5:
        n |= (1 << bits) - (1 << (bits - 32))   # top limb all ones
    b = rnd.randrange(n)
    e = rnd.getrandbits(bits)
    ln = bits // 8
    le = lambda x, l: x.to_bytes(l, "little").hex()
    o.append('  {"%s", "%s", "%s", "%s"},' % (le(n, ln), le(b, ln), le(e, ln), le(pow(b, e, n), ln)))
o.append("};")
open(sys.argv[1], "w").write("\n".join(o) + "\n")
